"""Generate rom_init_pkg.vhd: the contents of the chip ROMs (Quartus .mif files in the
MiSTer sources) as VHDL constants, which bram.vhd uses to initialize RAMs whose
mem_init_file names one of them. Vivado and GHDL both synthesize these without
needing to find the files at build time.

Usage: python3 gen_rom_init.py   (run from this directory)
"""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

# (constant name, .mif file, width)
ROMS = [
    ("DSP_PROG_ROM", "mister/chip/DSP/dsp11b23410_p.mif", 24),
    ("DSP_DATA_ROM", "mister/chip/DSP/dsp11b23410_d.mif", 16),
    ("CX4_DATA_ROM", "mister/chip/CX4/drom.mif", 24),
]


def read_mif(path: Path) -> list[int]:
    text = path.read_text()
    depth = int(re.search(r"DEPTH\s*=\s*(\d+)", text).group(1))
    words = [0] * depth
    body = text.split("CONTENT BEGIN", 1)[1]
    # "addr : value;" or "[first..last] : value;"
    for first, last, address, value in re.findall(
        r"(?:\[([0-9A-Fa-f]+)\.\.([0-9A-Fa-f]+)\]|([0-9A-Fa-f]+))\s*:\s*([0-9A-Fa-f]+)\s*;", body
    ):
        if address:
            first = last = address
        for a in range(int(first, 16), int(last, 16) + 1):
            words[a] = int(value, 16)
    return words


def main() -> None:
    lines = [
        "-- Generated by gen_rom_init.py from the MiSTer core's .mif files. Do not edit.",
        "",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "",
        "package rom_init_pkg is",
    ]
    for name, mif, width in ROMS:
        words = read_mif(HERE / mif)
        digits = (width + 3) // 4
        lines.append(f"\t-- {mif}")
        lines.append(
            f"\ttype {name}_T is array(0 to {len(words) - 1}) of std_logic_vector({width - 1} downto 0);"
        )
        lines.append(f"\tconstant {name} : {name}_T := (")
        values = [f'x"{w:0{digits}X}"' for w in words]
        for i in range(0, len(values), 8):
            end = "," if i + 8 < len(values) else ""
            lines.append("\t\t" + ", ".join(values[i : i + 8]) + end)
        lines.append("\t);")
    lines.append("end package;")
    (HERE / "rom_init_pkg.vhd").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
